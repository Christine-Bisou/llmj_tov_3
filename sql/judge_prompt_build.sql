$base = (
    SELECT
        t.*,
        $str(metadata.instruct_id) AS instruct_id,
        $last_dialog_query(dialog) AS instruct,
        ListFromRange(0u, CAST(ListLength(worker_ids) AS Uint64)) AS idxs
    FROM $input1 AS t
);

$flat_workers = (
    SELECT
        b.instruct_id,
        b.instruct,
        b.project_id,
        b.pool_id,
        b.answer_A,
        b.answer_B,

        -- Задание одно на строку, поэтому task_id идёт как есть: списка
        -- task_ids первый этап больше не отдаёт.
        b.task_id AS task_id,
        b.assignment_ids[idx] AS assignment_id,
        b.worker_ids[idx] AS worker_id,

        CAST(COALESCE(b.skip[idx], false) AS Bool) AS skip_worker,
        CAST(COALESCE(b.source_winner[idx], "") AS String) AS source_winner_worker,
        CAST(COALESCE(b.comments_A[idx], "") AS String) AS comments_A_worker,
        CAST(COALESCE(b.comments_B[idx], "") AS String) AS comments_B_worker,
        CAST(COALESCE(b.general_comments[idx], "") AS String) AS general_comment_worker
    FROM $base AS b
    -- Явно LIST BY: idxs получается из ListLength необязательной колонки, то
    -- есть List<Uint64>?, и простой FLATTEN BY не знает, что разворачивать.
    FLATTEN LIST BY (idxs AS idx)
);

