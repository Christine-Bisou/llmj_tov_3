# ЧТО СЧИТАЕТСЯ КОНТЕКСТОМ

Под контекстом понимаются особенности исходного запроса, задачи или ситуации пользователя, которые влияют на то, какой ответ уместнее. Это не общие слова про «хороший стиль» или «приятный тон», а особенности самого запроса или состояния пользователя.

Контекстом считаются, например:

* тема или задача запроса;
* домен запроса: медицина, право, финансы, психология и другие чувствительные или рискованные темы;
* требуемый формат ответа: кратко или подробно, пошагово или без лишних деталей, нейтрально или поддерживающе;
* уровень риска ошибки и уместная степень осторожности;
* эмоциональное состояние пользователя, если оно выражено в запросе: пользователь раздражен, тревожен, растерян, расстроен, рад, воодушевлен и т.п.;
* эмоциональная и коммуникативная рамка запроса: нужен ли спокойный, бережный, деловой, сочувственный или сдержанный тон;
* специальные ожидания пользователя, явно следующие из формулировки запроса.

Контекстная привязка — это явное упоминание особенностей самого запроса, прошлого диалога, задачи пользователя или обстоятельств ситуации при объяснении выбора между ответами.
Контекстная привязка может быть краткой. Достаточно короткого указания, почему названное различие между ответами важно именно для данного запроса, задачи или ситуации пользователя.

Простое описание качеств ответа или различий между ответами («живее», «сухой», «эмпатичный», «разъясняет шаги», «душный» и т.п.) само по себе не считается контекстной привязкой. Контекстная привязка возникает только тогда, когда качества ответа прямо связываются с особенностями исходного запроса или ситуации пользователя.

При оценке разрешается учитывать контекст, явно названный в любом из трех редакторских комментариев:

* [Комментарий редактора к Ответу A]
* [Комментарий редактора к Ответу B]
* [Финальный комментарий редактора]

Например, контекстной привязкой считаются формулировки вроде:

* «для медицинской темы такая осторожность уместна»;
* «в такой теме эмпатия особенно важна»;
* «для такого запроса более подробный ответ уместнее»;
* «в чувствительной ситуации сухой тон хуже работает»;
* «для тревожного пользователя более спокойный тон уместнее»;
* «для пошаговой технической инструкции такая структура воспринимается проще».


# Исключение
Если СКИП равен true, то редактор пропустил задание, и должен лишь указать причину пропуска (не объясняя ее), а не проводить сравнение ответов. Таким комментариям с указанием причины ставится - 5, без указанания причины пропуска 1.
Причины для пропуска:
- Прмяая речь на иностранном языке (хотя бы в одном ответе)
- Не показывается ответ (проблемы с отображением)
- Модели по разному понимают задачу

# ГЛАВНЫЙ ПРИНЦИП
Основной критерий качества — есть ли в комментарии явное сравнение ответов и понятно ли из него, почему выбран именно этот вердикт.

# ШКАЛА overall_score
- 5 — комментарий содержит прямое и самостоятельное сравнение A и B; причина выбора ясна, и есть хотя бы краткая отсылка к запросу, контексту или ситуации, например: «для такого запроса», «в таком случае», «для этой задачи». Этого достаточно для оценки 5; развернутая аргументация не требуется.
- 4 — комментарий самодостаточно объясняет выбор через сравнение ответов. В нем понятно, почему выбранный ответ лучше, даже если объяснение краткое. Допустимы формулировки через сравнительную степень: «точнее», «естественнее», «менее душно». Логика выбора считывается сразу и не требует додумывания, но привязки к запросу, контексту или ситуации нет.
- 3 — комментарий указывает на различие между ответами и в целом связывает его с выбором, но объяснение остается неполным, поверхностным или слишком общим. Понятно, в какую сторону сравнение, но не до конца понятно, почему это различие достаточно важно для выбора; часть логики приходится достраивать.
- 2 — комментарий называет достоинство или недостаток одного ответа, но не даёт явного сравнения с другим и плохо объясняет выбор.
- 1 — комментарий практически не объясняет выбор.

# ЖЁСТКОЕ ПРАВИЛО
Если в комментарии есть хотя бы одно явное различие между ответами и это различие связано с выбором,
overall_score не может быть ниже 3. Отсутствие примеров или подробного объяснения значимости не является причиной для снижения оценки.

# ВАЖНЫЕ ПОЯСНЕНИЯ
- overall_score — это не среднее арифметическое по частным критериям, а общая практическая ценность комментария для понимания выбора.
- Для высокой оценки не требуется полный разбор всех различий между ответами: достаточно одного ключевого различия, если оно явно связано с выбором.
- Не нужно снижать оценку только за отсутствие примеров из текста ответов, если различие уже чётко названо. Примеры в коментариях не требуются.
- Краткая привязка к запросу, контексту диалога, ситуации пользователя достаточна; подробное объяснение значимости не требуется.
- Ключевое различие между 4 и 5 — наличие хотя бы минимальной привязки к запросу, контексту или ситуации. Если в комментарии есть такая отсылка («для такого запроса», «в этой ситуации», «для этой задачи» и т.п.), это соответствует уровню 5; если привязки нет — уровню 4.
- Базовые характеристики качества (ясность, простота, уместность тона, отсутствие перегруженности, шаблонности, навязчивости и т.п.) не требуют дополнительного длинного обоснования.
- Если редактор опирается на маркеры (например, субъектность, эмпатия, тон, ясность, проактивность, перегруженность и т.п.), это считается валидным основанием для сравнения, если связь с выбором явно сформулирована.
- Для вердикта draw явное сравнение может быть выражено не только через противопоставление ответов, но и через указание на их равенство или одинаковое впечатление. Формулировки вроде "ответы одинаковые", "ощущение от ответов одинаковое", "оба звучат одинаково сухо" считаются полноценным сравнением, если по ним понятна причина ничьей.
- Для комментариев высокого качества (4–5) не следует предлагать формальные улучшения вроде «добавить примеры» или «раскрыть подробнее», если причина выбора уже ясна.
- Не рекомендуй улучшать комментарий за счет замечаний вне ToV-аспектов ответа: не советуй добавлять рассуждения о полезности, правдивости, полноте, структуре, списках, форматировании и других не-ToV характеристиках.
- Не проси приводить примеры из текста ответа или отдельно пояснять, чем выражен тот или иной маркер, если маркер уже назван. Предполагается, что такие места уже отмечены редактором в разметке маркерами.
- Если в одном ответе присутствуют положительные характеристики (например, эмпатия, субъектность, ясность, связки и т.п.), а в другом они отсутствуют или выражены слабее, это само по себе является достаточным основанием для сравнения и выбора, даже без подробного раскрытия или примеров.

